// ---------- 3) roles: catch the word that plays a role in the sentence ----------

export type Role = 'فعل' | 'فاعل' | 'مفعول به' | 'حرف جرّ' | 'اسم مجرور' | 'مبتدأ' | 'خبر';

export interface RoleSentence {
  words: string[];
  /** index of the word for each role it contains */
  roles: Partial<Record<Role, number>>;
}

/** 'word word word' + role letters: f=فعل s=فاعل o=مفعول j=جار m=مجرور b=مبتدأ k=خبر, one per word or '-' */
const rs = (text: string, tags: string): RoleSentence => {
  const words = text.split(' ');
  const map: Record<string, Role> = { f: 'فعل', s: 'فاعل', o: 'مفعول به', j: 'حرف جرّ', m: 'اسم مجرور', b: 'مبتدأ', k: 'خبر' };
  const roles: Partial<Record<Role, number>> = {};
  [...tags].forEach((t, i) => {
    if (map[t]) roles[map[t]] = i;
  });
  return { words, roles };
};

