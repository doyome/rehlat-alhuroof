/** Shuffle helper shared by the content builders (not exported to games: each game shuffles itself). */
const pick = <T>(a: T[], n: number) => [...a].sort(() => Math.random() - 0.5).slice(0, n);

// ---------- 1) sorting: put each card into the right box ----------

export interface SortItem {
  text: string;
  /** index into the stage's bins */
  bin: number;
}

export interface SortStage {
  id: string;
  title: string;
  /** what the child is sorting, shown on the HUD card, e.g. «اسم أم فعل أم حرف؟» */
  ask: string;
  bins: string[];
  items: SortItem[];
  rounds: number;
}

/** bins listed as groups: [label, 'word، word، …'] so the content reads like a textbook table */
const sort = (id: string, title: string, ask: string, groups: [string, string][], rounds = 8): SortStage => ({
  id,
  title,
  ask,
  bins: groups.map((g) => g[0]),
  items: groups.flatMap(([, words], bin) => words.split('، ').map((text) => ({ text, bin }))),
  rounds,
});

