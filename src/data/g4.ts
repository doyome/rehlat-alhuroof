export interface QuizItem {
  /** the question on the HUD card, e.g. «ضدّ كلمة: طويل» */
  q: string;
  /** options[0] is the right answer; games shuffle the order */
  options: string[];
}

export interface QuizStage {
  id: string;
  title: string;
  items: QuizItem[];
  rounds: number;
}

/** 'question | right | wrong | wrong' per line */
